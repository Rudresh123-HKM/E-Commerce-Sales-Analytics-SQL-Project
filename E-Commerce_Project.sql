(select date_trunc('month', order_date) as month,
sum(net_sales) as revenue 
from ecommerce_sales
group by month)

select month, revenue, lag(revenue) over(order by month) as previous_revenue,
   ROUND(
        (
            revenue - LAG(revenue) OVER (ORDER BY month)
