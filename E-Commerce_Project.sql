/*
Business Problem:
Segment customers based on purchasing behaviour.

Business Impact:
Helps businesses identify Champions, Loyal Customers
and At-Risk Customers for targeted marketing.

SQL Concepts:
CTE
NTILE
CASE
Window Functions
*/
WITH rfm_base AS (
    SELECT
        customer_id,
        CURRENT_DATE - MAX(order_date) AS recency,
        COUNT(DISTINCT order_id) AS frequency,
        SUM(net_sales) AS monetary
    FROM ecommerce_sales
    GROUP BY customer_id
),
rfm_scores AS (
    SELECT
        customer_id,
        NTILE(5) OVER (ORDER BY recency DESC) AS r_score,
        NTILE(5) OVER (ORDER BY frequency) AS f_score,
        NTILE(5) OVER (ORDER BY monetary) AS m_score
    FROM rfm_base
)
SELECT
    customer_id,
    r_score,
    f_score,
    m_score,

    CASE
        WHEN r_score >= 4
         AND f_score >= 4
         AND m_score >= 4
        THEN 'Champions'

        WHEN r_score >= 3
         AND f_score >= 3
         AND m_score >= 3
        THEN 'Loyal Customers'

        WHEN r_score >= 4
         AND f_score <= 2
        THEN 'Potential Loyalists'

        WHEN r_score <= 2
         AND f_score >= 3
        THEN 'At Risk'

        ELSE 'Others'
    END AS customer_segment
FROM rfm_scores;

/*
Business Problem:
Identify the total lifetime value generated by each customer.

Why This Analysis Matters:
Customer Lifetime Value (CLV) helps businesses understand
which customers contribute the most revenue over their entire
relationship with the company.

Business Impact:
- Identify high-value customers
- Improve customer retention strategies
- Optimize marketing spend
- Design loyalty and reward programs
- Focus resources on profitable customer segments

Approach:
