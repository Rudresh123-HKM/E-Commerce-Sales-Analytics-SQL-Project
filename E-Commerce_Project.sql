/*
Business Problem:
Ensure customer data integrity by identifying duplicate customer records.

Why This Analysis Matters:
Duplicate customer records can lead to inaccurate reporting,
inflated customer counts, incorrect Customer Lifetime Value (CLV),
and misleading customer segmentation results.

Approach:
- Group records by customer_id.
- Count the number of occurrences of each customer_id.
- Return only those customer IDs appearing more than once.

SQL Concepts Used:
- GROUP BY
- COUNT()
- HAVING

Expected Outcome:
Any customer_id returned by this query represents a potential
duplicate record that should be investigated before performing
business analysis.

*/
select customer_id, count(*) from customer_master 
group by customer_id
having count(*) >1;

/*
Business Problem:
Identify order records that reference products that do not exist
in the product catalog.

Why This Analysis Matters:
Missing product references indicate data integrity issues
between transactional and master data tables.

These issues can:
- Produce inaccurate sales reports
- Create incomplete product performance analysis
- Impact inventory and profitability calculations
- Cause reporting errors in dashboards

Approach:
- Compare product IDs from order_items with product_catalog.
- Return records where a matching product is not found.
- Investigate missing products before performing business analysis.

SQL Concepts Used:
- LEFT JOIN
- NULL Checking
- Data Quality Validation

Expected Outcome:
The query should return all order items that reference
non-existent products in the product catalog.
A clean dataset should ideally return zero rows.

*/
select*from order_items oi
join product_catalog pc
on oi.product_id = pc.product_id
where pc.product_id is null;

